// Copies the pure matching engine from src/ into the find-matches Edge Function so the app and the
// server score matches with the SAME code. Deno needs explicit ".ts" imports, so specifiers are rewritten.
// Run after editing any of these files:  node scripts/sync-edge-engine.mjs
// tests/unit/edgeEngine.test.ts fails if the copies drift.
import { readFileSync, writeFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'
import path from 'node:path'

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')
export const ENGINE_FILES = {
  'src/domain/types.ts': 'types.ts',
  'src/domain/matching.ts': 'matching.ts',
  'src/domain/measure.ts': 'measure.ts',
  'src/lib/corridor.ts': 'corridor.ts',
  'src/lib/geo.ts': 'geo.ts',
}
export const ENGINE_DIR = 'supabase/functions/find-matches/engine'
const SPECIFIERS = {
  '@/domain/types': './types.ts', './types': './types.ts',
  '@/domain/matching': './matching.ts', './matching': './matching.ts',
  '@/lib/corridor': './corridor.ts', '@/lib/geo': './geo.ts',
}

export function engineCopy(source) {
  const body = source.replace(/from '([^']+)'/g, (m, spec) => {
    if (!(spec in SPECIFIERS)) throw new Error(`Engine file imports '${spec}', which is not part of the shared engine`)
    return `from '${SPECIFIERS[spec]}'`
  })
  return `// GENERATED by scripts/sync-edge-engine.mjs — edit the file in src/ and re-run the script.\n${body}`
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  for (const [from, to] of Object.entries(ENGINE_FILES)) {
    writeFileSync(path.join(root, ENGINE_DIR, to), engineCopy(readFileSync(path.join(root, from), 'utf8')))
    console.log(`${from} → ${ENGINE_DIR}/${to}`)
  }
}
